package vpn

import (
	"errors"
	"fmt"
	"io/fs"
	"net/netip"
	"os"
	"os/exec"

	log "github.com/sirupsen/logrus"
)

const (
	resolvConf       = "/etc/resolv.conf"
	resolvConfBackup = "/etc/resolv.conf.ytelenet-backup"
)

// setSystemDNS makes the system resolve names through dns on the tunnel
// interface. sing-tun doesn't configure DNS on linux, so without it the old
// DNS server stays in use (and is unreachable or leaks the queries).
//
// Returns a function that restores the previous configuration.
func setSystemDNS(iface string, dns netip.Addr) (func(), error) {
	if resolvedActive() {
		return setResolvedDNS(iface, dns)
	}
	return setResolvConfDNS(resolvConf, resolvConfBackup, dns)
}

func resolvedActive() bool {
	if _, err := exec.LookPath("resolvectl"); err != nil {
		return false
	}
	return exec.Command("systemctl", "is-active", "--quiet", "systemd-resolved").Run() == nil
}

// setResolvedDNS sets the DNS server of the tunnel interface in
// systemd-resolved, and the "~." routing domain makes it used for all names
func setResolvedDNS(iface string, dns netip.Addr) (func(), error) {
	commands := [][]string{
		{"dns", iface, dns.String()},
		{"domain", iface, "~."},
		{"default-route", iface, "true"},
	}

	for _, args := range commands {
		out, err := exec.Command("resolvectl", args...).CombinedOutput()
		if err != nil {
			_ = exec.Command("resolvectl", "revert", iface).Run()
			return nil, fmt.Errorf("resolvectl %v: %w: %s", args, err, out)
		}
	}
	log.Infof("Set DNS %v on %v via systemd-resolved", dns, iface)

	return func() {
		// the interface is usually gone by now, and the config with it
		_ = exec.Command("resolvectl", "revert", iface).Run()
	}, nil
}

// setResolvConfDNS replaces resolv.conf, keeping the original (a file or a
// symlink) as backup
func setResolvConfDNS(path, backup string, dns netip.Addr) (func(), error) {
	restoreResolvConf(path, backup)

	if err := os.Rename(path, backup); err != nil && !errors.Is(err, fs.ErrNotExist) {
		return nil, fmt.Errorf("failed to back up %v: %w", path, err)
	}

	content := fmt.Sprintf("# generated by ytelenet, the original is in %v\nnameserver %v\n", backup, dns)
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		restoreResolvConf(path, backup)
		return nil, fmt.Errorf("failed to write %v: %w", path, err)
	}
	log.Infof("Set DNS %v in %v", dns, path)

	return func() { restoreResolvConf(path, backup) }, nil
}

// restoreResolvConf puts the backup back, if there is one (it can be left
// over if ytelenet was killed)
func restoreResolvConf(path, backup string) {
	if _, err := os.Lstat(backup); err != nil {
		return
	}

	if err := os.Rename(backup, path); err != nil {
		log.Errorf("Failed to restore %v from %v: %v", path, backup, err)
	}
}

func cleanupLeftoverDNS() {
	restoreResolvConf(resolvConf, resolvConfBackup)
}
